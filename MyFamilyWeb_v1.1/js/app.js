    const getCurrentLanguage = () => {
        const stored = localStorage.getItem('myfamilyweb-language');
        return stored && translations[stored] ? stored : 'vi';
    };

    const getNestedValue = (obj, path) => {
        if (obj && Object.prototype.hasOwnProperty.call(obj, path)) {
            return obj[path];
        }
        return path.split('.').reduce((current, segment) => current && current[segment], obj);
    };

    const applyTranslations = () => {
        const lang = getCurrentLanguage();
        const pack = translations[lang] || translations.vi;
        document.documentElement.lang = lang;
        document.body.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');

        document.querySelectorAll('[data-i18n]').forEach((node) => {
            const value = getNestedValue(pack, node.dataset.i18n);
            if (typeof value === 'string') {
                node.textContent = value;
            }
        });

        const select = document.getElementById('site-language-select');
        if (select) {
            select.value = lang;
        }
    };

    const injectLanguageSelector = () => {
        if (document.getElementById('site-language-select')) {
            return;
        }

        const wrapper = document.createElement('div');
        wrapper.className = 'language-switcher';
        wrapper.innerHTML = `
            <label class="language-label" for="site-language-select" aria-label="Select language">
                <i class="fas fa-globe"></i>
            </label>
            <select id="site-language-select" aria-label="Language selector">
                ${Object.entries(languageOptions).map(([code, label]) => `<option value="${code}">${label}</option>`).join('')}
            </select>
        `;

        const headerTools = document.querySelector('.nav-bar');
        if (headerTools) {
            headerTools.appendChild(wrapper);
        } else {
            document.body.appendChild(wrapper);
        }

        const selector = document.getElementById('site-language-select');
        selector.value = getCurrentLanguage();
        selector.addEventListener('change', (event) => {
            localStorage.setItem('myfamilyweb-language', event.target.value);
            applyTranslations();
        });
    };

    if (!document.querySelector('meta[name="viewport"]')) {
        const meta = document.createElement('meta');
        meta.name = 'viewport';
        meta.content = 'width=device-width, initial-scale=1.0, maximum-scale=1.0, user-scalable=no';
        document.head.prepend(meta);
    }

    window.isMobile = ('ontouchstart' in window) || (navigator.maxTouchPoints > 0);

    document.addEventListener('touchmove', (event) => {
        if (event.target && event.target.classList && event.target.classList.contains('game-control')) {
            event.preventDefault();
        }
    }, { passive: false });

    injectLanguageSelector();
    applyTranslations();
